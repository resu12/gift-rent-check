import {secretbox} from './vendor/tweetnacl-secretbox.js';
import {sha256} from './ton-price-decoder.js';
import {utf8Bytes} from './personal-analytics.js';

const hex = bytes => Array.from(bytes, b => b.toString(16).padStart(2,'0')).join('');
function unhex(value, max) {
  if (typeof value !== 'string' || !value.length || value.length > max || !/^(?:[a-f0-9]{2})+$/.test(value)) throw new Error('Invalid refresh envelope');
  return Uint8Array.from(value.match(/../g), pair => parseInt(pair,16));
}
/** Anonymous cookie/challenge are encrypted in volatile client memory only.
 * A unique, database-reserved attempt ID plus provider challenge derives the
 * 192-bit nonce. IDs must never be reused; attempts are single-use. The secret
 * 256-bit key is generated by Node's CSPRNG locally and deployed privately.
 * No random generator is needed in the Serverless runtime.
 */
export function createMarketappSessionBox(keyHex) {
  const key = unhex(keyHex,64);
  if (key.length !== 32) throw new Error('Invalid refresh key');
  return {
    seal(payload) {
      if (!payload || typeof payload !== 'object' || !/^[a-f0-9]{64}$/.test(payload.attempt_id) || typeof payload.challenge !== 'string' || !payload.challenge.length) throw new Error('Invalid refresh envelope');
      const bytes = utf8Bytes(JSON.stringify(payload));
      if (bytes.length > 8192) throw new Error('Invalid refresh envelope');
      const nonce = sha256(utf8Bytes(`marketapp-refresh-box-v1\0${payload.attempt_id}\0${payload.challenge}`)).slice(0,24);
      const ciphertext = secretbox(bytes,nonce,key);
      return `01${hex(nonce)}${hex(ciphertext)}`;
    },
    open(envelope) {
      const bytes = unhex(envelope, 16500);
      if (bytes[0] !== 1 || bytes.length < 42) throw new Error('Invalid refresh envelope');
      const plaintext = secretbox.open(bytes.slice(25),bytes.slice(1,25),key);
      if (!plaintext || plaintext.length > 8192) throw new Error('Invalid refresh envelope');
      try {
        // JSON contains only bounded ASCII cookie/challenge/address metadata.
        if (plaintext.some(byte => byte > 127)) throw new Error();
        return JSON.parse(Array.from(plaintext,byte => String.fromCharCode(byte)).join(''));
      } finally {plaintext.fill(0);}
    },
  };
}
