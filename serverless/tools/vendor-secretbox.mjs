// Reproduce the ESM wrapper from the already locked TweetNaCl 1.0.3 source.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root = new URL('../../frontend/node_modules/.pnpm/tweetnacl@1.0.3/node_modules/tweetnacl/', import.meta.url);
const packageInfo = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
if (packageInfo.version !== '1.0.3') throw new Error('Unexpected TweetNaCl version');
const original = await readFile(new URL('nacl-fast.js', root), 'utf8');
const ending = "})(typeof module !== 'undefined' && module.exports ? module.exports : (self.nacl = self.nacl || {}));";
if (!original.startsWith('(function(nacl) {') || !original.trimEnd().endsWith(ending)) throw new Error('Unexpected TweetNaCl wrapper');
const directory = new URL('../tgcloud/lib/vendor/', import.meta.url);
await mkdir(directory, {recursive:true});
const header = '// TweetNaCl.js 1.0.3; public domain. Generated by tools/vendor-secretbox.mjs.\n// Only the export wrapper is adapted; cryptographic implementation is unchanged.\nconst nacl = {};\n';
const adapter = `// BEGIN PUBLIC ED25519 POINT ADAPTER
// Use the unchanged upstream point routines to require a canonical, nonzero
// point in the prime-order subgroup. No field/signature algorithm is replaced.
nacl.isValidEd25519Point = function(encoded) {
  if (!(encoded instanceof Uint8Array) || encoded.length !== 32) return false;
  var q = [gf(), gf(), gf(), gf()], p = [gf(), gf(), gf(), gf()];
  if (unpackneg(q, encoded)) return false;
  var canonical = new Uint8Array(32), identity = new Uint8Array(32);
  identity[0] = 1; pack(canonical, q);
  canonical[31] &= 127;
  var y = new Uint8Array(encoded); y[31] &= 127;
  if (vn(canonical, 0, y, 0, 32) !== 0 || vn(y, 0, identity, 0, 32) === 0) return false;
  scalarmult(p, q, new Uint8Array(L)); pack(canonical, p);
  return vn(canonical, 0, identity, 0, 32) === 0;
};
// END PUBLIC ED25519 POINT ADAPTER
`;
await writeFile(new URL('tweetnacl-secretbox.js', directory), header + original.replace(ending, adapter + '})(nacl);\nexport const secretbox = nacl.secretbox;\nexport const verifyDetached = nacl.sign.detached.verify;\nexport const isValidEd25519Point = nacl.isValidEd25519Point;'));
await writeFile(new URL('TWEETNACL-LICENSE.txt', directory), await readFile(new URL('LICENSE', root)));
await writeFile(new URL('tweetnacl-source.json', directory), JSON.stringify({package:'tweetnacl',version:'1.0.3',source:'https://github.com/dchest/tweetnacl-js/tree/v1.0.3',file:'nacl-fast.js',sha256:createHash('sha256').update(original).digest('hex')},null,2)+'\n');
